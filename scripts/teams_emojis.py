#!/usr/bin/env python3
"""Regenerate src/miniteams/teams_emojis.py from Teams' public emoticon metadata.

    uv run ./scripts/teams_emojis.py [metadata URL]

The URL's hash changes with each catalog release: take the current one from the
`personal-expressions/v1/metadata/<hash>/en-us.json` request Teams web makes (browser devtools,
or the teams-for-linux HTTP cache). It is a public CDN file, no sign-in.
"""

import re
import sys
import unicodedata
from pathlib import Path
from typing import Any

import httpx

URL = (
    "https://statics.teams.cdn.office.net/evergreen-assets/personal-expressions/v1/metadata/"
    "ec4576179210cde40ce5494513213583/en-us.json"
)
OUT = Path(__file__).resolve().parent.parent / "src" / "miniteams" / "teams_emojis.py"


def literal(text: str) -> str:
    # ZWJ, variation selectors and code points newer than Python's Unicode stay readable as escapes.
    return '"' + "".join(c if c.isprintable() and c not in '"\\' else _escape(ord(c)) for c in text) + '"'


def _escape(point: int) -> str:
    return f"\\u{point:04x}" if point < 0x10000 else f"\\U{point:08x}"


def _entries(metadata: dict[str, Any]) -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for category in metadata["categories"]:
        for emo in category["emoticons"]:
            # A few legacy emoticons (`support`, `oreo`) have no character, only Teams' `(name)` text.
            if not emo["unicode"].isascii():
                out.setdefault(emo["id"], emo)
    return out


def table(metadata: dict[str, Any]) -> dict[str, str]:
    return {name: emo["unicode"] for name, emo in _entries(metadata).items()}


def _words(text: str) -> list[str]:
    return re.findall(r"[a-z0-9]+", text.lower())


def _match(description: str, stems: set[str]) -> tuple[float, int]:
    """(share, count) of the description's words found among the Unicode name's stems."""
    words = _words(description)
    hits = sum(w[:4] in stems for w in words)
    return (hits / len(words) if words else 0.0, hits)


def plain(metadata: dict[str, Any]) -> dict[str, str]:
    """Character → the name to send it as, for characters Teams names several times: the character's
    own `<hex>_<name>` id, else the entry whose description best matches its Unicode name (`soccerball`,
    not `bartlett`). Absent when no description matches the Unicode name."""
    groups: dict[str, list[dict[str, Any]]] = {}
    for emo in _entries(metadata).values():
        groups.setdefault(emo["unicode"].replace("\ufe0f", ""), []).append(emo)
    out: dict[str, str] = {}
    for char, emos in groups.items():
        if len(emos) < 2:
            continue
        # Python's Unicode names are older than Teams' descriptions: compare word stems.
        stems = {w[:4] for w in _words(" ".join(unicodedata.name(c, "") for c in char))}
        best = max(emos, key=lambda emo: _match(emo["description"], stems))  # first of equals: catalog order
        if own := [e["id"] for e in emos if e["id"].partition("_")[0] == f"{ord(char[0]):04x}"]:
            out[char] = own[0]
        elif _match(best["description"], stems)[0] > 0:
            out[char] = best["id"]
    return out


def diverse(metadata: dict[str, Any]) -> list[str]:
    """Ids Teams draws in skin tones (`<id>-tone1`…), its own art whether or not the character takes one."""
    return [name for name, emo in _entries(metadata).items() if emo.get("diverse")]


def module(
    url: str, last_modified: str, emojis: dict[str, str], send: dict[str, str], toned: list[str]
) -> str:
    """The module's source; both strings come from outside, so they only appear as escaped literals."""
    rows = "".join(f"    {literal(k)}: {literal(v)},\n" for k, v in emojis.items())
    sends = "".join(f"    {literal(k)}: {literal(v)},\n" for k, v in send.items())
    tones = "".join(f"        {literal(k)},\n" for k in toned)
    return (
        '"""Teams emoticon id → character, in Teams\' catalog order, and the plain name to send for a\n'
        "character Teams names several times, and the ids it tones.\n\n"
        'Generated by scripts/teams_emojis.py, do not edit."""\n\n'
        f"# Source: {literal(url)}\n"
        f"# Last-Modified: {literal(last_modified)}\n"
        f"TEAMS_EMOJIS: dict[str, str] = {{\n{rows}}}\n\n"
        f"TEAMS_PLAIN: dict[str, str] = {{\n{sends}}}\n\n"
        f"TEAMS_DIVERSE: frozenset[str] = frozenset(\n    {{\n{tones}    }}\n)\n"
    )


def main() -> None:
    url = sys.argv[1] if len(sys.argv) > 1 else URL
    resp = httpx.get(url, timeout=30.0)
    resp.raise_for_status()
    metadata = resp.json()
    last_modified = resp.headers.get("last-modified", "?")
    source = module(url, last_modified, table(metadata), plain(metadata), diverse(metadata))
    OUT.write_text(source, encoding="utf-8")


if __name__ == "__main__":
    main()
