#!/usr/bin/env python3
"""Regenerate src/miniteams/emojibase.py from emojibase's shortcode sets.

    uv run ./scripts/emojibase_names.py [emojibase-data version]

Names are emojibase's own set, then GitHub's for the characters' other names (`+1`, `hankey`).
"""

import re
import sys
from pathlib import Path
from typing import Any

import httpx
from teams_emojis import literal  # scripts/ is on sys.path when run as a script

VERSION = "18.0.0"
BASE = "https://cdn.jsdelivr.net/npm/emojibase-data@{}/en/"
PRESETS = ("emojibase", "github")  # the first of two equal names wins
OUT = Path(__file__).resolve().parent.parent / "src" / "miniteams" / "emojibase.py"
# The page opens the popup on these characters only.
NAME_RE = re.compile(r"[a-z0-9_+-]+")


def table(data: list[dict[str, Any]], presets: list[dict[str, str | list[str]]]) -> dict[str, str]:
    """Name → character; skin-tone variants left out, they would crowd the completion."""
    chars = {e["hexcode"]: e["emoji"] for e in data}
    out: dict[str, str] = {}
    for preset in presets:
        for hexcode, names in preset.items():
            if hexcode not in chars:
                continue
            for name in [names] if isinstance(names, str) else names:
                if NAME_RE.fullmatch(name):
                    out.setdefault(name, chars[hexcode])
    return dict(sorted(out.items()))


def module(url: str, names: dict[str, str]) -> str:
    rows = "".join(f"    {literal(k)}: {literal(v)},\n" for k, v in names.items())
    return (
        '"""Shortcode → character: emojibase\'s names, then GitHub\'s.\n\n'
        'Generated by scripts/emojibase_names.py, do not edit."""\n\n'
        f"# Source: {literal(url)}\n"
        f"EMOJIBASE: dict[str, str] = {{\n{rows}}}\n"
    )


def main() -> None:
    base = BASE.format(sys.argv[1] if len(sys.argv) > 1 else VERSION)
    with httpx.Client(timeout=30.0) as client:

        def get(path: str) -> Any:
            resp = client.get(base + path)
            resp.raise_for_status()
            return resp.json()

        names = table(get("data.json"), [get(f"shortcodes/{p}.json") for p in PRESETS])
    OUT.write_text(module(base, names), encoding="utf-8")


if __name__ == "__main__":
    main()
